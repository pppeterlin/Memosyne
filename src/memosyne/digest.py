"""
The Digest — a map of the vault that fits in a context window.

Top-k retrieval cannot answer "where have I travelled?" or "what happened
in what order?": those need the whole picture, not the five nearest chunks.
The digest gives agents that picture as two small Markdown files built
*deterministically* from memory frontmatter — no LLM, no index:

  <vault>/_digest/timeline.md   every dated memory, grouped by year and month
  <vault>/_digest/entities.md   places, people, events and periods → memories

Both are rebuilt from scratch on every run and contain no timestamps, so an
unchanged vault always produces byte-identical files. The folder starts with
an underscore, so its contents are never indexed or enriched as memories.

  memosyne digest                  # rebuild both files
  memosyne digest --include-chats  # also list AI chat transcripts
  memosyne digest --print timeline # write to stdout instead of the vault
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from memosyne.link_extractor import _split_frontmatter, extract_from_content
from memosyne.paths import data_root, iter_memory_files, rel_memory_path

DIGEST_DIR = "_digest"
CHAT_DOMAIN = "20_AI_Chats"
MAX_PATHS_PER_ENTITY = 6
SUMMARY_CHARS = 80

_DATE_RE = re.compile(r"(\d{4})-(\d{2})-(\d{2})")
_STEM_DATE_RE = re.compile(r"^(\d{2})(\d{2})(\d{2})(?!\d)")
_H1_RE = re.compile(r"^# +(.+?)\s*$", re.M)
_HEADER = ("> Generated by `memosyne digest` from memory frontmatter. "
           "Do not edit — rerun to refresh.")


@dataclass
class Entry:
    path: str                       # vault-relative, usable with read_file
    date: str = ""                  # YYYY-MM-DD, or "" when unknown
    title: str = ""
    period: str = ""
    summary: str = ""
    locations: list[str] = field(default_factory=list)
    people: list[str] = field(default_factory=list)
    events: list[str] = field(default_factory=list)


def _memory_date(fm: dict, stem: str) -> str:
    for key in ("date_created", "date"):
        m = _DATE_RE.search(str(fm.get(key, "")))
        if m:
            return m.group(0)
    m = _STEM_DATE_RE.match(stem)      # journal convention: YYMMDD.md
    if m and 1 <= int(m.group(2)) <= 12 and 1 <= int(m.group(3)) <= 31:
        return f"20{m.group(1)}-{m.group(2)}-{m.group(3)}"
    return ""


def _one_line(text: object, limit: int) -> str:
    s = " ".join(str(text or "").split())
    return s if len(s) <= limit else s[: limit - 1] + "…"


def collect(root: Path | None = None, include_chats: bool = False) -> list[Entry]:
    """Read every memory's frontmatter into a sorted list of entries."""
    base = root or data_root()
    entries: list[Entry] = []
    for md_file in iter_memory_files(base):
        rel = rel_memory_path(md_file, base)
        if rel.startswith(DIGEST_DIR + "/"):
            continue
        if not include_chats and rel.startswith(CHAT_DOMAIN + "/"):
            continue
        try:
            content = md_file.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        fm, body = _split_frontmatter(content)
        if str(fm.get("dormant", "")).lower() == "true":
            continue
        heading = _H1_RE.search(body)
        ext = extract_from_content(content)
        ents = ext.get("entities", {})
        entries.append(Entry(
            path=rel,
            date=_memory_date(fm, md_file.stem),
            title=_one_line(fm.get("title") or (heading.group(1) if heading else md_file.stem), 60),
            period=_one_line(ext.get("period"), 40),
            summary=_one_line(fm.get("summary"), SUMMARY_CHARS),
            locations=list(ents.get("locations", [])),
            people=list(ents.get("people", [])),
            events=list(ents.get("events", [])),
        ))
    entries.sort(key=lambda e: (e.date or "9999", e.path))
    return entries


# ─── Rendering ────────────────────────────────────────────────

def render_timeline(entries: list[Entry]) -> str:
    dated = [e for e in entries if e.date]
    undated = [e for e in entries if not e.date]
    span = f"{dated[0].date[:7]} → {dated[-1].date[:7]}" if dated else "no dated memories"
    lines = ["# Timeline", "", _HEADER, f"> {len(entries)} memories · {span}", ""]

    def row(e: Entry, label: str) -> str:
        parts = [f"- **{label}** `{e.path}` — {e.title}"]
        if e.period:
            parts.append(f"period: {e.period}")
        if e.locations:
            parts.append("places: " + ", ".join(e.locations))
        if e.people:
            parts.append("people: " + ", ".join(e.people))
        if e.events:
            parts.append("events: " + ", ".join(e.events))
        if e.summary and not (e.locations or e.people or e.events):
            parts.append(e.summary)
        return " · ".join(parts)

    year = month = ""
    for e in dated:
        if e.date[:7] != month and month:
            lines.append("")           # blank line closes the previous month
        if e.date[:4] != year:
            year = e.date[:4]
            lines += [f"## {year}", ""]
        if e.date[:7] != month:
            month = e.date[:7]
            lines += [f"### {month}", ""]
        lines.append(row(e, e.date[8:]))
    if dated:
        lines.append("")
    if undated:
        lines += ["## Undated", ""]
        lines += [row(e, "—") for e in undated]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _entity_section(title: str, index: dict[str, list[Entry]]) -> list[str]:
    lines = [f"## {title} ({len(index)})", ""]
    for name, mems in sorted(index.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        dates = sorted(m.date for m in mems if m.date)
        span = ""
        if dates:
            span = dates[0][:7] if dates[0][:7] == dates[-1][:7] else f"{dates[0][:7]} → {dates[-1][:7]}"
        paths = [f"`{m.path}`" for m in mems[:MAX_PATHS_PER_ENTITY]]
        more = f", +{len(mems) - MAX_PATHS_PER_ENTITY} more" if len(mems) > MAX_PATHS_PER_ENTITY else ""
        head = f"- **{name}** ({len(mems)})" + (f" · {span}" if span else "")
        lines.append(f"{head}: {', '.join(paths)}{more}")
    if not index:
        lines.append("_None recorded yet — entities come from enrichment (`memosyne enrich`)._")
    lines.append("")
    return lines


def render_entities(entries: list[Entry]) -> str:
    places: dict[str, list[Entry]] = defaultdict(list)
    people: dict[str, list[Entry]] = defaultdict(list)
    events: dict[str, list[Entry]] = defaultdict(list)
    periods: dict[str, list[Entry]] = defaultdict(list)
    for e in entries:
        for name in dict.fromkeys(e.locations):
            places[name].append(e)
        for name in dict.fromkeys(e.people):
            people[name].append(e)
        for name in dict.fromkeys(e.events):
            events[name].append(e)
        if e.period:
            periods[e.period].append(e)

    lines = ["# Entity index", "", _HEADER,
             f"> {len(places)} places · {len(people)} people · "
             f"{len(events)} events · {len(periods)} periods", ""]
    lines += _entity_section("Places", places)
    lines += _entity_section("People", people)
    lines += _entity_section("Events", events)
    lines += _entity_section("Periods", periods)
    return "\n".join(lines).rstrip() + "\n"


RENDERERS = {"timeline": render_timeline, "entities": render_entities}


def digest_dir(root: Path | None = None) -> Path:
    return (root or data_root()) / DIGEST_DIR


def build(root: Path | None = None, include_chats: bool = False,
          entries: list[Entry] | None = None) -> dict[str, Path]:
    """Rebuild every digest file. Returns {kind: path}."""
    base = root or data_root()
    if entries is None:
        entries = collect(base, include_chats=include_chats)
    out_dir = digest_dir(base)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for kind, render in RENDERERS.items():
        path = out_dir / f"{kind}.md"
        text = render(entries)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
        written[kind] = path
    return written


def read(kind: str, root: Path | None = None, year: str = "") -> str:
    """Return one digest as text, building it first if it does not exist."""
    if kind not in RENDERERS:
        raise ValueError(f"unknown digest: {kind!r} (choose from {sorted(RENDERERS)})")
    path = digest_dir(root) / f"{kind}.md"
    if not path.exists():
        build(root)
    text = path.read_text(encoding="utf-8")
    if kind == "timeline" and year:
        m = re.search(rf"^## {re.escape(year)}\n(.*?)(?=^## |\Z)", text, re.M | re.S)
        return f"# Timeline — {year}\n\n{m.group(1).strip()}\n" if m else \
            f"No dated memories in {year}."
    return text


def main() -> int:
    ap = argparse.ArgumentParser(
        prog="memosyne digest",
        description="Rebuild the deterministic vault digests (timeline + entity index).",
    )
    ap.add_argument("--include-chats", action="store_true",
                    help="also list AI chat transcripts")
    ap.add_argument("--print", dest="print_kind", choices=sorted(RENDERERS),
                    help="print one digest to stdout instead of writing files")
    args = ap.parse_args()

    entries = collect(include_chats=args.include_chats)
    if args.print_kind:
        print(RENDERERS[args.print_kind](entries), end="")
        return 0

    written = build(entries=entries)
    if not entries:
        print("The Vault is empty. The digest holds only silence.")
        return 0
    print(f"🌊 The digest is renewed — {len(entries)} memories mapped.")
    for kind, path in written.items():
        print(f"   {kind:9} {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
